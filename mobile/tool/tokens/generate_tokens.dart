// Generates lib/core/theme/tokens.dart from the web's token sheet.
//
// Run through tools/mobile-tokens.sh, never by hand-editing the output: a token change is a re-run
// (docs/features/mobile-app.md, Design). The source is frontend/src/styles/tokens.css rather than
// the design system's styles.css because the dark palette exists only there (design/README.md,
// Known gaps) — the web transcribed it from the canvas once, and the phone must not do it twice.
//
//   dart run tool/tokens/generate_tokens.dart          writes the file
//   dart run tool/tokens/generate_tokens.dart --check  fails if the committed file is stale
import 'dart:io';

/// Where the tokens come from, relative to mobile/.
const String sourcePath = '../frontend/src/styles/tokens.css';

/// The web's components sheet, for the one role token it defines (`--field-border`).
const String componentsPath = '../frontend/src/styles/components.css';

/// Where they go.
const String outputPath = 'lib/core/theme/tokens.dart';

/// Colour roles every widget may use, in the order they are emitted.
const List<String> roles = [
  'bg',
  'surface',
  'card',
  'text',
  'accent',
  'accent-2',
  'divider',
  'accent-text',
  'muted',
  'primary',
  'primary-hover',
  'primary-active',
  'on-primary',
  'goal-track',
  'field-border',
];

/// Ramp steps carried for both themes. They do not change with the theme; roles do.
const List<String> ramps = ['neutral', 'accent', 'accent-2'];
const List<int> steps = [100, 200, 300, 400, 500, 600, 700, 800, 900];

Future<void> main(List<String> args) async {
  final css = File(sourcePath).readAsStringSync();
  final components = File(componentsPath).readAsStringSync();
  final generated = generateTokens(css, components);
  final output = File(outputPath);
  if (args.contains('--check')) {
    if (!output.existsSync() || output.readAsStringSync() != generated) {
      stderr.writeln(
        '$outputPath is stale: run tools/mobile-tokens.sh and commit the result.',
      );
      exit(1);
    }
    return;
  }
  output.writeAsStringSync(generated);
}

/// The whole output file, deterministically, from the two stylesheets' text.
String generateTokens(String css, String components) {
  final light = _block(css, ':root {');
  final dark = _block(css, ":root[data-theme='dark'] {");
  final field = _block(components, ':root {');

  // The light theme names no card colour: the mobile artboards draw rows on neutral-100. Like
  // --color-goal-track on the web, this is a role composed of an existing token, not a new value.
  final lightVars = {
    ...light,
    'color-card': light['color-card'] ?? 'var(--color-neutral-100)',
    'field-border': field['field-border']!,
  };
  final darkVars = {
    ...light,
    ...dark,
    'field-border': field['field-border']!,
  };

  final out = StringBuffer()
    ..writeln('// GENERATED by tools/mobile-tokens.sh from')
    ..writeln('// frontend/src/styles/tokens.css. Do not edit by hand: change the design')
    ..writeln('// project, re-extract the web sheet, and re-run the script.')
    ..writeln('//')
    ..writeln('// ignore_for_file: public_member_api_docs')
    ..writeln()
    ..writeln("import 'package:flutter/painting.dart';")
    ..writeln()
    ..writeln("/// One theme's colour roles. Widgets read these, never a literal colour.")
    ..writeln('final class ColorTokens {')
    ..writeln('  const ColorTokens({');
  for (final role in roles) {
    out.writeln('    required this.${_camel(role)},');
  }
  out
    ..writeln('  });')
    ..writeln();
  for (final role in roles) {
    out.writeln('  final Color ${_camel(role)};');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln("/// The light theme (the design system's own).")
    ..writeln('const ColorTokens lightColors = ColorTokens(');
  for (final role in roles) {
    out.writeln('  ${_camel(role)}: ${_dart(_resolve(_roleVar(role), lightVars))},');
  }
  out
    ..writeln(');')
    ..writeln()
    ..writeln('/// The dark theme: warm near-black grounds, accents stepped up to their 400 tints.')
    ..writeln('const ColorTokens darkColors = ColorTokens(');
  for (final role in roles) {
    out.writeln('  ${_camel(role)}: ${_dart(_resolve(_roleVar(role), darkVars))},');
  }
  out
    ..writeln(');')
    ..writeln()
    ..writeln('/// The tonal ramps, the same in both themes.')
    ..writeln('abstract final class RampTokens {');
  for (final ramp in ramps) {
    for (final step in steps) {
      final name = '${_camel(ramp)}$step';
      out.writeln(
        '  static const Color $name = ${_dart(_resolve('color-$ramp-$step', lightVars))};',
      );
    }
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// Spacing, in logical pixels.')
    ..writeln('abstract final class SpaceTokens {');
  for (final entry in light.entries.where((e) => e.key.startsWith('space-'))) {
    out.writeln(
      '  static const double s${entry.key.substring(6)} = ${_px(entry.value)};',
    );
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// Corner radii, in logical pixels.')
    ..writeln('abstract final class RadiusTokens {');
  for (final entry in light.entries.where((e) => e.key.startsWith('radius-'))) {
    out.writeln(
      '  static const double ${entry.key.substring(7)} = ${_px(entry.value)};',
    );
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// Font families: the first name in each web stack. Bundled, never fetched.')
    ..writeln('abstract final class FontTokens {')
    ..writeln("  static const String heading = '${_family(light['font-heading']!)}';")
    ..writeln("  static const String body = '${_family(light['font-body']!)}';")
    ..writeln(
      '  static const int headingWeight = ${light['font-heading-weight']!.trim()};',
    )
    ..writeln('}')
    ..writeln()
    ..writeln('/// The type scale.')
    ..writeln('///')
    ..writeln('/// KNOWN GAP (design/README.md): the token sheet carries no type scale, on the web')
    ..writeln("/// or anywhere. These are the sizes the design's 390-wide artboards draw, read")
    ..writeln('/// once and kept here so no widget invents its own. Settle a real scale in the')
    ..writeln('/// design project and this block becomes generated like the rest.')
    ..writeln('abstract final class TypeScaleTokens {');
  for (final size in _typeScale.entries) {
    out.writeln('  static const double ${size.key} = ${size.value};');
  }
  out.writeln('}');
  return out.toString();
}

const Map<String, String> _typeScale = {
  'display': '26.0', // a screen's title (Caprasimo)
  'title': '20.0', // a sheet's or card's heading
  'body': '15.0', // a row's primary line, body text
  'label': '13.0', // chips, buttons, form labels
  'small': '12.0', // a row's secondary line, hints
  'overline': '11.0', // date headers, uppercase, tracked
  'nav': '10.0', // the bottom navigation's labels
};

String _roleVar(String role) =>
    role == 'field-border' ? 'field-border' : 'color-$role';

/// The declarations inside the first block whose selector line starts with [selector].
Map<String, String> _block(String css, String selector) {
  final start = css.indexOf(selector);
  if (start < 0) {
    throw StateError('no "$selector" block in the stylesheet');
  }
  final open = css.indexOf('{', start);
  var depth = 0;
  var end = open;
  for (var i = open; i < css.length; i++) {
    if (css[i] == '{') depth++;
    if (css[i] == '}') {
      depth--;
      if (depth == 0) {
        end = i;
        break;
      }
    }
  }
  final body = css
      .substring(open + 1, end)
      .replaceAll(RegExp(r'/\*.*?\*/', dotAll: true), '');
  final vars = <String, String>{};
  for (final match in RegExp(r'--([a-z0-9-]+)\s*:\s*([^;]+);').allMatches(body)) {
    vars[match.group(1)!] = match.group(2)!.trim();
  }
  return vars;
}

/// A colour as 0xAARRGGBB, following var() references and color-mix() through [vars].
int _resolve(String name, Map<String, String> vars) {
  final value = vars[name];
  if (value == null) {
    throw StateError('token --$name is not defined');
  }
  return _colour(value, vars);
}

int _colour(String value, Map<String, String> vars) {
  final v = value.trim();
  final reference = RegExp(r'^var\(--([a-z0-9-]+)\)$').firstMatch(v);
  if (reference != null) {
    return _resolve(reference.group(1)!, vars);
  }
  final hex = RegExp(r'^#([0-9a-fA-F]{6})$').firstMatch(v);
  if (hex != null) {
    return 0xFF000000 | int.parse(hex.group(1)!, radix: 16);
  }
  final mix = RegExp(
    r'^color-mix\(in srgb,\s*(.+?)\s+(\d+)%,\s*(.+)\)$',
  ).firstMatch(v);
  if (mix != null) {
    final a = _colour(mix.group(1)!, vars);
    final weight = int.parse(mix.group(2)!) / 100;
    final other = mix.group(3)!.trim();
    if (other == 'transparent') {
      final alpha = (weight * 255).round();
      return (alpha << 24) | (a & 0x00FFFFFF);
    }
    final b = _colour(other, vars);
    int channel(int shift) {
      final ca = (a >> shift) & 0xFF;
      final cb = (b >> shift) & 0xFF;
      return (ca * weight + cb * (1 - weight)).round() & 0xFF;
    }

    return 0xFF000000 | (channel(16) << 16) | (channel(8) << 8) | channel(0);
  }
  throw StateError('cannot read a colour from "$value"');
}

String _dart(int argb) =>
    'Color(0x${argb.toRadixString(16).padLeft(8, '0').toUpperCase()})';

String _px(String value) {
  final number = value.trim().replaceAll('px', '');
  return number.contains('.') ? number : '$number.0';
}

String _family(String stack) =>
    stack.split(',').first.trim().replaceAll("'", '').replaceAll('"', '');

String _camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first +
      parts.skip(1).map((p) => p.isEmpty ? '' : p[0].toUpperCase() + p.substring(1)).join();
}
